/**
 * Generates src/generated/transaction-batch-validator.ts, a dependency-free request validator
 * for runtimes without express-openapi-validator (the Supabase Edge Function).
 *
 * Run after changing powersync-reference-write-api.openapi.yaml:
 *   pnpm generate-edge-validator
 *
 * The output mirrors express-openapi-validator's request checks: no type coercion, extra
 * properties allowed, and its int64 format expressed as the same numeric bounds.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { Ajv } from 'ajv';
import standalone from 'ajv/dist/standalone/index.js';
import { parse } from 'yaml';

type Schema = Record<string, unknown>;

const SPEC = new URL('../powersync-reference-write-api.openapi.yaml', import.meta.url);
export const OUTPUT = new URL('../src/generated/transaction-batch-validator.ts', import.meta.url);
const ROOT = 'TransactionBatch';
const REF_PREFIX = '#/components/schemas/';

/** Rewrites OpenAPI-only constructs into plain JSON Schema and collects referenced schema names. */
function toJsonSchema(node: unknown, refs: Set<string>): unknown {
  if (Array.isArray(node)) return node.map((item) => toJsonSchema(item, refs));
  if (!node || typeof node !== 'object') return node;
  const out: Schema = {};
  for (const [key, value] of Object.entries(node)) {
    if (key === '$ref' && typeof value === 'string' && value.startsWith(REF_PREFIX)) {
      const name = value.slice(REF_PREFIX.length);
      refs.add(name);
      out.$ref = `#/definitions/${name}`;
    } else if (key === 'format' && (value === 'int64' || value === 'int32')) {
      // Same bounds as express-openapi-validator's formats; type: integer already checks integrality.
      const bits = value === 'int64' ? 63 : 31;
      out.minimum = (-2) ** bits;
      out.maximum = 2 ** bits - 1;
    } else if (key === 'description') {
      continue;
    } else {
      out[key] = toJsonSchema(value, refs);
    }
  }
  return out;
}

export function generate(): string {
  const spec = parse(readFileSync(SPEC, 'utf8')) as { components: { schemas: Record<string, Schema> } };
  const definitions: Record<string, unknown> = {};
  const pending = [ROOT];
  while (pending.length > 0) {
    const name = pending.pop()!;
    if (name in definitions) continue;
    const refs = new Set<string>();
    definitions[name] = toJsonSchema(spec.components.schemas[name], refs);
    pending.push(...refs);
  }

  const ajv = new Ajv({ code: { source: true, esm: true }, strict: true, allErrors: false, coerceTypes: false });
  const validate = ajv.compile({ $ref: `#/definitions/${ROOT}`, definitions });
  // CommonJS module: Node exposes its exports object as the default import.
  const code = standalone.default(ajv, validate);
  if (/\brequire\(|^import\s/m.test(code)) {
    throw new Error('Generated validator has runtime imports; it must stay dependency-free for Edge.');
  }

  return (
    '// Generated by scripts/generate-edge-validator.ts from powersync-reference-write-api.openapi.yaml. Do not edit.\n' +
    '// @ts-nocheck\n' +
    code +
    '\n'
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUTPUT, generate());
  console.log(`Wrote ${fileURLToPath(OUTPUT)}`);
}
